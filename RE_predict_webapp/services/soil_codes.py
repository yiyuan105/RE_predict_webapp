def soil_type_name(raw_code: str | int | float | None) -> str | None:
    """把 SOIL_ID 编码换算成土类名称，无法识别时返回带编码的占位名。"""
    code = _normalise(raw_code)
    if code is None:
        return None
    return SOIL_CLASS_NAMES.get(code[:2], f"未收录土类({code[:2]})")


def _normalise(raw_code: str | int | float | None) -> str | None:
    if raw_code is None:
        return None
    try:
        return str(int(float(raw_code))).zfill(3)
    except (TypeError, ValueError):
        return None
